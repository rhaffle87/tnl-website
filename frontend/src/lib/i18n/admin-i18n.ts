export type AdminStringKey = keyof typeof ADMIN_STRINGS.en;

const AdminLocaleContext = createContext<"en" | "id" | null>(null);

export function AdminLocaleProvider({ children }: { children: ReactNode }) {
  const { locale } = useLocale();
  return createElement(AdminLocaleContext.Provider, { value: locale }, children);
}

export function useAdminT(): (key: AdminStringKey) => string {
  const locale = useContext(AdminLocaleContext);
  const resolved = locale === "id" ? "id" : "en";
  return (key: AdminStringKey) => ADMIN_STRINGS[resolved][key];
}
