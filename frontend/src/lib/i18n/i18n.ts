export type StringKey = keyof (typeof STRINGS)["en"];

interface LocaleContextValue {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: StringKey) => string;
}

export const LocaleContext = createContext<LocaleContextValue>({
  locale: "id",
  setLocale: () => {},
  t: (key) => STRINGS.id[key],
});

export function useLocale(): LocaleContextValue {
  return useContext(LocaleContext);
}

/** Pick the localized twin of a content field: `bio` / `bio_id`. */
export function pick(
  locale: Locale,
  en: string | null | undefined,
  id: string | null | undefined,
): string {
  if (locale === "id") return (id && id.trim()) || en || "";
  return (en && en.trim()) || id || "";
}

/** Read `field` or `field_id` from a loosely typed block props object. */
export function pickProp(
  locale: Locale,
  props: Record<string, unknown>,
  key: string,
): string {
  const en = typeof props[key] === "string" ? (props[key] as string) : "";
  const idKey = `${key}_id`;
  // An Indonesian field that is PRESENT but empty is deliberate (e.g. a hero whose
  // accent word ends the Indonesian phrase) — honour it instead of falling back to English.
  if (locale === "id" && typeof props[idKey] === "string") return props[idKey] as string;
  const idv = typeof props[idKey] === "string" ? (props[idKey] as string) : "";
  return pick(locale, en, idv);
}

